#!/bin/sh
# Generates the decisions index from the files in docs/decisions/.
# One file per decision (ai/RULES.md rule 13); the index is never edited by hand.
set -eu
dir=$(dirname "$0")/../docs/decisions
echo "# Decisions"
echo
echo "Generated by \`make decisions-index\`. Do not edit; add a \`D-NNN-slug.md\` file instead."
echo
echo "| Id | Date | Status | Title |"
echo "|---|---|---|---|"
for f in $(ls "$dir"/D-*.md 2>/dev/null | sort); do
  base=$(basename "$f")
  id=$(echo "$base" | sed -E 's/^(D-[0-9]+)-.*/\1/')
  title=$(grep -m1 -E '^# ' "$f" | sed -E 's/^# (D-[0-9]+:? *)?//')
  date=$(grep -m1 -E '^\*\*Date:\*\*' "$f" | sed -E 's/^\*\*Date:\*\* *//')
  status=$(grep -m1 -E '^\*\*Status:\*\*' "$f" | sed -E 's/^\*\*Status:\*\* *//')
  echo "| [$id]($base) | $date | $status | $title |"
done
